"""
Automated Code Testing and Self-Healing Engine.

Tests code files generated by Ollambo for:
  - Syntax errors (AST parsing for Python, JSON decoding for JSON, brace/tag matching)
  - Runtime errors / import compilation
  - Automated diagnosis and self-healing: feeds error messages back to the model
    to fix bugs before outputting final code.
"""

from __future__ import annotations

import ast
import json
import re
import sys
import tempfile
from pathlib import Path
from typing import Callable

from core.code_writer import clean_code_fence
from core.ollama_client import OllamaClient
from core.prompts import CODE_FIXER_USER, CODE_TESTER_SYSTEM


def validate_syntax(filename: str, code: str) -> tuple[bool, str]:
    """
    Validate syntax for a given code file.
    Returns (is_valid, error_message).
    """
    if not code or not code.strip():
        return False, "Generated code is empty."

    # Python syntax validation
    if filename.endswith(".py"):
        try:
            ast.parse(code, filename=filename)
        except SyntaxError as e:
            line_text = f" (line {e.lineno}, col {e.offset}): {e.text.strip() if e.text else ''}" if e.lineno else ""
            return False, f"SyntaxError in `{filename}`{line_text}\n{e.msg}"
        except Exception as e:
            return False, f"Python parse error in `{filename}`: {e}"

        try:
            compile(code, filename, "exec")
        except Exception as e:
            return False, f"Python compile error in `{filename}`: {e}"

    # JSON validation
    elif filename.endswith(".json"):
        try:
            json.loads(code)
        except json.JSONDecodeError as e:
            return False, f"JSONDecodeError in `{filename}` at line {e.lineno}, col {e.colno}: {e.msg}"

    # JavaScript / TypeScript basic brace balance check
    elif filename.endswith((".js", ".jsx", ".ts", ".tsx")):
        open_braces = code.count("{") - code.count("}")
        open_parens = code.count("(") - code.count(")")
        open_brackets = code.count("[") - code.count("]")
        if open_braces != 0 or open_parens != 0 or open_brackets != 0:
            return False, (
                f"Unbalanced delimiters in `{filename}`: "
                f"braces balance={open_braces}, parens balance={open_parens}, brackets balance={open_brackets}"
            )

    # HTML / XML basic check
    elif filename.endswith((".html", ".htm", ".xml")):
        if "<html" in code.lower() and "</html" not in code.lower():
            return False, f"Unclosed <html> tag in `{filename}`"

    return True, ""


def run_automated_tests(
    filename: str,
    code: str,
    all_files: dict[str, str] | None = None,
) -> tuple[bool, str]:
    """
    Perform deep static and dry-run tests on generated code.
    Returns (passed, diagnostic_message).
    """
    # 1. Syntax check first
    valid, err = validate_syntax(filename, code)
    if not valid:
        return False, err

    # 2. Check for obvious placeholders left by LLM
    placeholder_patterns = [
        (r"#\s*TODO:\s*implement", "Unimplemented TODO placeholder found"),
        (r"#\s*insert code here", "Incomplete placeholder found"),
        (r"def\s+\w+\([^)]*\):\s*\.\.\.\s*$", "Ellipsis stub function without implementation"),
    ]
    for pattern, warning in placeholder_patterns:
        if re.search(pattern, code, re.IGNORECASE):
            return False, f"Quality check failed in `{filename}`: {warning}"

    # 3. Dry-run test for Python files containing tests or self-contained scripts
    if filename.endswith(".py") and ("unittest" in code or "pytest" in code or "__main__" in code):
        try:
            with tempfile.TemporaryDirectory() as tmpdir:
                tmp_path = Path(tmpdir)
                parts = [p for p in filename.replace("\\", "/").split("/") if p and p != "."]
                target = tmp_path.joinpath(*parts)
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(code, encoding="utf-8")

                if all_files:
                    for dep_name, dep_code in all_files.items():
                        if dep_name != filename:
                            dep_parts = [p for p in dep_name.replace("\\", "/").split("/") if p and p != "."]
                            dep_path = tmp_path.joinpath(*dep_parts)
                            dep_path.parent.mkdir(parents=True, exist_ok=True)
                            dep_path.write_text(dep_code, encoding="utf-8")

                import os, subprocess
                env = dict(os.environ)
                env["PYTHONPATH"] = str(tmp_path)
                res = subprocess.run(
                    [sys.executable, "-m", "py_compile", str(target)],
                    capture_output=True,
                    text=True,
                    timeout=5,
                    cwd=str(tmp_path),
                    env=env,
                )
                if res.returncode != 0:
                    return False, f"py_compile failed for `{filename}`:\n{res.stderr.strip()}"
        except Exception:
            pass

    return True, "All tests passed successfully."


def test_and_repair(
    ollama_url: str,
    model: str,
    filename: str,
    code: str,
    step_desc: str,
    all_files: dict[str, str] | None = None,
    num_ctx: int = 8192,
    max_retries: int = 2,
    stop_flag: Callable[[], bool] | None = None,
    on_repair_status: Callable[[str], None] | None = None,
) -> tuple[str, bool, str]:
    """
    Tests the code and automatically repairs any caught bugs using a self-healing LLM loop.
    Returns (final_code, tests_passed, status_summary).
    """
    current_code = code
    passed, err = run_automated_tests(filename, current_code, all_files)
    if passed:
        return current_code, True, "Passed on initial test"

    client = OllamaClient(ollama_url)

    for attempt in range(1, max_retries + 1):
        if stop_flag and stop_flag():
            return current_code, False, "Cancelled by user"

        if on_repair_status:
            on_repair_status(f"🔧 Testing caught issue in `{filename}`: {err}. Auto-fixing (attempt {attempt}/{max_retries})…")

        prompt = CODE_FIXER_USER.format(
            file=filename,
            step_desc=step_desc,
            code=current_code,
            error=err,
        )

        messages = [
            {"role": "system", "content": CODE_TESTER_SYSTEM},
            {"role": "user", "content": prompt},
        ]

        import os
        optimal_threads = min(8, max(2, os.cpu_count() or 4))
        chunks: list[str] = []
        for chunk in client.chat_stream(
            model=model,
            messages=messages,
            options={
                "num_ctx": num_ctx,
                "temperature": 0.2,
                "top_p": 0.9,
                "num_thread": optimal_threads,
            },
            stop_flag=stop_flag,
        ):
            if stop_flag and stop_flag():
                return current_code, False, "Cancelled by user"
            content = chunk.get("message", {}).get("content", "")
            if content:
                chunks.append(content)
            if chunk.get("done", False):
                break

        repaired = clean_code_fence("".join(chunks))
        if repaired and repaired.strip():
            current_code = repaired

        passed, err = run_automated_tests(filename, current_code, all_files)
        if passed:
            if on_repair_status:
                on_repair_status(f"✅ Tester Agent successfully fixed `{filename}` on attempt {attempt}!")
            return current_code, True, f"Repaired on attempt {attempt}"

    return current_code, False, f"Remaining issue after {max_retries} attempts: {err}"
